/** Lightweight `useT` for the player window — no React context required. */
export function usePlayerT() {
  const [lang, setLang] = useState<string>(() => {
    try { return localStorage.getItem('cc-lang') || 'en'; } catch { return 'en'; }
  });

  useEffect(() => {
    const onStorage = (event: StorageEvent) => {
      if (event.key === 'cc-lang') setLang(event.newValue || 'en');
    };
    window.addEventListener('storage', onStorage);
    return () => window.removeEventListener('storage', onStorage);
  }, []);

  return useCallback((key: PlayerKey, vars?: Record<string, string | number>): string => {
    let text: string = dicts[lang]?.[key] ?? en[key];
    if (vars) {
      for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, String(value));
    }
    return text;
  }, [lang]);
}
